import { Body, Controller, Get, HttpCode, HttpStatus, Post, Query, Req } from '@nestjs/common';
import { ApiOperation, ApiTags } from '@nestjs/swagger';
import { Throttle } from '@nestjs/throttler';
import { IsOptional, IsString, Length, MaxLength } from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Public } from '../common/decorators';
import { LicenseValidationService, type ValidateRequest } from './license-validation.service';

export class ValidateLicenseDto implements ValidateRequest {
  @ApiProperty() @IsString() @Length(10, 64)
  licenseKey!: string;

  @ApiProperty({ description: 'Stable machine fingerprint generated by the client' })
  @IsString() @Length(8, 500)
  deviceFingerprint!: string;

  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(180)
  deviceName?: string;

  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(40)
  platform?: string;

  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(80)
  osVersion?: string;

  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(40)
  appVersion?: string;
}

@ApiTags('License Validation (public)')
@Controller('validations')
export class LicenseValidationController {
  constructor(private readonly validation: LicenseValidationService) {}

  @Public()
  @Post('validate')
  @HttpCode(HttpStatus.OK)
  // Rate limited per IP: this endpoint is public by necessity.
  @Throttle({ default: { limit: 60, ttl: 60_000 } })
  @ApiOperation({
    summary: 'Periodic license check called by the customer application',
    description:
      'Always returns HTTP 200 with a status field, so the client gets a definitive answer even for failures.',
  })
  validate(@Body() dto: ValidateLicenseDto, @Req() req: any) {
    return this.validation.validate(dto, req);
  }

  @Get('history')
  @ApiOperation({ summary: 'Validation history (owner panel only)' })
  async history(@Query('licenseId') licenseId?: string, @Query() rest: Record<string, any> = {}) {
    return this.validation.history({
      licenseId: licenseId ? Number(licenseId) : undefined,
      status: rest.status,
      page: rest.page ? Number(rest.page) : undefined,
      limit: rest.limit ? Number(rest.limit) : undefined,
    });
  }
}
